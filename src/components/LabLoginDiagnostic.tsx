import { useState } from 'react'

type CheckState = 'unchecked' | 'checking' | 'verified' |
  'not-verified' | 'route-missing' | 'html-instead-of-json' |
  'function-rejected' | 'unexpected-response' | 'failed'

/**
 * Explicit, read-only check. Never transmits personal observations,
 * local backups, passwords, phone keys or IndexedDB content.
 */
export function LabLoginDiagnostic() {
  const [check, setCheck] = useState<CheckState>('unchecked')

  async function checkLogin() {
    if (check === 'checking') return
    setCheck('checking')
    try {
      const response = await fetch('/.netlify/functions/lab-login-status', {
        method: 'GET',
        cache: 'no-store',
        credentials: 'same-origin',
        redirect: 'error'
      })
      const type = (response.headers.get('content-type') || '').toLowerCase()
      // Never treat a static HTML fallback, Netlify access page or 404 as
      // authentication. A 404 JSON generated by OUR function is distinct
      // from a CDN 404 / missing route.
      if (!type.includes('application/json')) {
        setCheck(response.status === 404 ? 'route-missing' : 'html-instead-of-json')
        return
      }
      const data: unknown = await response.json()
      const isObject = data !== null && typeof data === 'object' && !Array.isArray(data)
      if (response.status === 404) {
        // Our function explicitly emits JSON {status:'unavailable'} when its
        // strict site, hostname or requested path guard rejects invocation.
        setCheck(isObject && 'status' in data && data.status === 'unavailable'
          ? 'function-rejected' : 'route-missing')
        return
      }
      if (response.status === 401 || response.status === 403) {
        setCheck('not-verified')
        return
      }
      if (!response.ok) {
        setCheck('unexpected-response')
        return
      }
      if (isObject &&
        'authenticated' in data && data.authenticated === true &&
        'status' in data && data.status === 'verified-private-login' &&
        'permission' in data && data.permission === 'read-only' &&
        'cloudSync' in data && data.cloudSync === 'not-configured') {
        setCheck('verified')
      } else {
        setCheck('unexpected-response')
      }
    } catch {
      setCheck('failed')
    }
  }

  const messages: Record<CheckState, string> = {
    unchecked: '尚未检查。测试不会读取本机记录或连接数据库。',
    checking: '正在询问 Netlify 是否确认当前登录……',
    verified: '已验证 Netlify 私有站点登录。仅有只读身份确认；云端同步未开启。',
    'not-verified': '未能确认 Netlify 登录，请检查是否通过私有站点登录。',
    'route-missing': '未找到登录诊断 JSON 接口（HTTP 404）。可能是 Netlify 路由或部署配置未生效，不能判断登录状态。',
    'html-instead-of-json': '登录诊断返回了 HTML 网页，而不是接口 JSON。可能是访问保护页面或静态站点回退，不能判断登录状态。',
    'function-rejected': 'Netlify Function 已响应，但它的站点、域名或路径安全校验没有通过；这不是登录失败。',
    'unexpected-response': '诊断接口响应异常；没有足够证据判断登录状态。',
    failed: '诊断请求未完成，可能是网络、访问保护或服务暂不可用。'
  }

  return (
    <section role="region" aria-label="只读登录诊断"
      style={{ marginTop: 16, paddingTop: 12, borderTop: '1px solid #bfa66d' }}>
      <strong>Netlify 登录诊断 · 只读</strong>
      <p>仅确认当前浏览器的 Netlify 登录是否经过验证；不显示账号 ID、邮箱，不上传虚构记录，也不启用云同步。</p>
      <div className="isolated-lab-actions">
        <button type="button" onClick={() => void checkLogin()}
          disabled={check === 'checking'}>
          {check === 'checking' ? '检查中……' : '检查 Netlify 登录（只读）'}
        </button>
      </div>
      <p role="status" aria-live="polite">{messages[check]}</p>
    </section>
  )
}
